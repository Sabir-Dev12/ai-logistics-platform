using Logistics.DbScript;
using Logistics.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;

// Emits runnable T-SQL for the LogisticsDb database: the schema from the EF model, and a test dataset.
//
// This needs NO database connection — EF builds the DDL from the model — which is why it works in an environment
// where SQL Server is unreachable. That matters here: the sandbox cannot reach the local instance (TCP is
// disabled for SQLEXPRESS and named pipes are blocked), so a .bak could not be produced. The scripts can be.
//
// Usage:
//   Logistics.DbScript schema <output.sql> [databaseName]
//   Logistics.DbScript seed   <output.sql> [motDePasseAdmin] [motDePasseUtilisateur]

const string clairAdmin = "Admin123!";
const string clairUtilisateur = "User123!";

// A deliberately unroutable server: GenerateCreateScript never opens a connection, and a real address would
// suggest otherwise.
const string chaineInutilisee =
    "Data Source=(localdb)\\MSSQLLocalDB;Initial Catalog=LogisticsDb;Integrated Security=True";

if (args.Length < 2)
{
    Console.Error.WriteLine("usage: Logistics.DbScript <schema|seed> <output.sql> [args...]");
    return 1;
}

var mode = args[0].ToLowerInvariant();
var chemin = Path.GetFullPath(args[1]);

var options = new DbContextOptionsBuilder<LogisticsDbContext>()
    .UseSqlServer(chaineInutilisee)
    .Options;

await using var db = new LogisticsDbContext(options);

switch (mode)
{
    case "schema":
    {
        var baseNom = args.Length > 2 ? args[2] : "LogisticsDb";

        var entetes = $"""
-- ============================================================================================
--  {baseNom} — schema generated from the EF Core model
-- ============================================================================================
--  Generated by Database/Tools/DbScript, not written by hand: it is the DDL EF derives from the
--  model, so it cannot disagree with what the application expects. The legacy project contains no
--  DDL at all, so this is the only authoritative schema for these tables.
--
--  Run it against a server you can reach:
--      sqlcmd -S "(localdb)\MSSQLLocalDB" -E -d LogisticsDb -i Create-Schema.sql
--
--  Then, to produce a .bak for another machine:
--      sqlcmd -S ".\SQLEXPRESS" -E -Q "BACKUP DATABASE [{baseNom}] TO DISK='C:\temp\{baseNom}.bak' WITH INIT, COMPRESSION"
-- ============================================================================================
--  Entity types : {db.Model.GetEntityTypes().Count()}
--  Tables       : {db.Model.GetEntityTypes().Count(t => t.GetTableName() is not null)}
--  Generated    : {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC
-- ============================================================================================

""";

        await File.WriteAllTextAsync(chemin, entetes + db.Database.GenerateCreateScript());

        Console.WriteLine($"schema ecrit     : {chemin}");
        Console.WriteLine($"tables           : {db.Model.GetEntityTypes().Count(t => t.GetTableName() is not null)}");
        Console.WriteLine($"taille           : {new FileInfo(chemin).Length:N0} octets");
        break;
    }

    case "seed":
    {
        var admin = args.Length > 2 ? args[2] : clairAdmin;
        var utilisateur = args.Length > 3 ? args[3] : clairUtilisateur;

        await File.WriteAllTextAsync(chemin, Seed.Generer(admin, utilisateur));

        Console.WriteLine($"jeu de donnees ecrit : {chemin}");
        Console.WriteLine($"comptes              : admin / {admin}   et   dupont / {utilisateur}");
        break;
    }

    case "hash":
    {
        // Prints the legacy encoding for each candidate, so a pass_word can be produced for t_personnel
        // without guessing. Uses the same routine the API verifies against.
        if (args.Length < 2)
        {
            Console.Error.WriteLine("usage: Logistics.DbScript hash <motDePasse> [autres...]");
            return 1;
        }

        foreach (var clair in args.Skip(1))
        {
            var encode = Logistics.Domain.Entities.Resources.MotDePasseLegacy.Coder(clair);
            var ok = Logistics.Domain.Entities.Resources.MotDePasseLegacy.Verifier(clair, encode);
            Console.WriteLine($"{clair,-24} -> {encode,-22} verifie={ok}");
        }

        break;
    }
    default:
        Console.Error.WriteLine($"mode inconnu: {mode} (attendu: schema ou seed)");
        return 1;
}

return 0;
